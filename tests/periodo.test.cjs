const assert=require('node:assert/strict'), D=require('../js/data_core.js');
const sheet=(headers,rows)=>D.sheetProfile('Campaña', [headers,...rows]);
const h=['Código de productora','Cooperativa'];
let r=D.importProfiles([sheet([...h,'quintales_acopiados_2027','ingreso_principal_pen_2027','fecha_nacimiento_beneficiaria'],[['P1','Nueva',27,1000,'2000-12-30']])],{fileName:'exportacion_2025.xlsx'});
assert.equal(r.audit.period,2027);
assert.equal(r.audit.ageCutoff,'2027-12-31');
assert.equal(r.records[0].age,27);
assert.equal(r.records[0].qq,27);
assert.equal(r.records[0].income,1000);
r=D.importProfiles([sheet([...h,'quintales_acopiados','Año'],[['P1','Nueva',2,2029]])]);
assert.equal(r.audit.period,2029);
r=D.importProfiles([sheet([...h,'quintales_acopiados','fecha_nacimiento_beneficiaria'],[['P1','Nueva',2,'2000-12-30']])],{fileName:'exportacion_2027.xlsx'});
assert.equal(r.audit.period,null);
assert.equal(r.audit.ageCutoff,null);
assert.equal(r.records[0].age,null);
assert.equal(r.records[0].qq,2);
assert.throws(()=>D.importProfiles([sheet([...h,'Año'],[['P1','Nueva',2027],['P2','Nueva',2028]])]),/mezcla periodos/);
assert.throws(()=>D.importProfiles([sheet([...h,'quintales_acopiados_2027','Año'],[['P1','Nueva',1,2028]])]),/mezcla periodos/);
const both=[...h,'quintales_acopiados_2025','quintales_acopiados_2027'];
assert.equal(D.inferMap(both).qq,undefined);
assert.deepEqual(D.ambiguousFields(both),['qq']);
